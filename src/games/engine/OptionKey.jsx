import './OptionKey.css'

/**
 * Номер клавіші в кутку варіанта.
 *
 * Без нього клавіатурне керування лишається загадкою: підказка каже «1–4», але
 * яка цифра якому варіанту відповідає — доводиться рахувати очима щоразу, а в
 * половині ігор варіанти ще й перемішуються щопроби.
 *
 * aria-hidden навмисно: для того, хто слухає сторінку, кнопка вже має власну
 * назву, і зайве число в ній тільки заважало б.
 */
function OptionKey({ n }) {
  return (
    <span className="option-key" aria-hidden="true">
      {n}
    </span>
  )
}

export default OptionKey
