/**
 * Щоденна мета.
 *
 * Серія днів показувала, що дитина зробила, але не казала, що робити зараз:
 * «5 днів поспіль» — це нагорода за вчора. Мета перетворює серію на дію,
 * зрозумілу з першого погляду: скільки ігор лишилось сьогодні.
 *
 * Три спроби — не випадкове число: це приблизно один урок. Менше не тримає
 * серію осмисленою, більше перетворює вправу на зобов'язання, а дитину, яка
 * не встигла, — на винну.
 */
export const DAILY_TARGET = 3

export function dailyGoal(attemptsToday, target = DAILY_TARGET) {
  const done = Math.max(0, attemptsToday)
  return {
    done,
    target,
    left: Math.max(0, target - done),
    reached: done >= target,
    /* Смужка не переповнюється: після мети вона просто повна. */
    percent: Math.min(100, Math.round((done / target) * 100)),
  }
}

/**
 * Що сказати дитині. Текст не дорікає за невиконане: дитина, яка зайшла й
 * побачила докір, наступного разу може не зайти.
 */
export function dailyGoalText(goal) {
  if (goal.reached) return 'Мету на сьогодні виконано. Можна грати далі просто так.'
  if (goal.done === 0) return `Сьогодні ще нічого. Зіграй ${goal.target} гри — і день зараховано.`
  return goal.left === 1 ? 'Лишилась одна гра.' : `Лишилось ${goal.left} гри.`
}
