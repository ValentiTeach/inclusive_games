/**
 * Календарний день — за годинником дитини, а не за Гринвічем.
 *
 * Скрізь у проєкті день виводився як `new Date().toISOString().slice(0, 10)`.
 * Це UTC-доба, а діти живуть за київським часом (UTC+2 взимку, +3 влітку).
 * Наслідок: усе, що сталося між північчю і третьою ночі, потрапляло у
 * вчорашній день. Серія днів обривалася на рівному місці, щоденна мета
 * показувала вчорашній прогрес, а дедлайн завдання зсувався на дві-три години.
 *
 * Мить гри як і раніше зберігається в UTC (`toISOString`) — це правильно, бо
 * мить одна на весь світ. Місцевим має бути тільки день, до якого ту мить
 * відносять.
 */

/**
 * @param value мить (Date, рядок ISO або мілісекунди); за умовчанням — зараз
 * @returns день у вигляді YYYY-MM-DD за місцевим часом
 */
export function localDay(value = Date.now()) {
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return null

  /*
   * Складається вручну, а не через Intl.DateTimeFormat('sv-SE'): той спосіб
   * тримається на тому, що шведський формат випадково збігається з ISO. Тут
   * видно, що саме збирається, і зламати це оновленням бібліотеки локалей
   * неможливо.
   */
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

/**
 * Попередній календарний день.
 *
 * Рядок розбирається як UTC-опівніч і крок робиться теж у UTC. Це і є захист
 * від переходу на літній час: у місцевому часі доба двічі на рік має 23 або 25
 * годин, і будь-яка арифметика там ризикує дати не той день. У UTC доба завжди
 * рівно доба, а рядки, що сюди приходять, уже місцеві — переводити їх ще раз
 * нема куди.
 *
 * Саме тому тут байдуже, setUTCDate чи віднімання доби в мілісекундах: у
 * UTC-просторі це одне й те саме. Помилкою було б рахувати в місцевому часі.
 */
export function dayBefore(day) {
  const date = new Date(`${day}T00:00:00Z`)
  if (Number.isNaN(date.getTime())) return null

  date.setUTCDate(date.getUTCDate() - 1)
  return date.toISOString().slice(0, 10)
}
