import { describe, it, expect, vi, afterEach } from 'vitest'
import { localDay, dayBefore } from './day'

/*
 * Увесь набір іде за київським часом (див. vite.config.js). Саме там UTC-доба
 * розходиться з календарною, і саме цю розбіжність тут і перевіряють.
 */

describe('місцевий день', () => {
  afterEach(() => {
    vi.useRealTimers()
  })

  it('удень збігається з UTC-добою', () => {
    expect(localDay(new Date('2026-06-15T12:00:00Z'))).toBe('2026-06-15')
  })

  /**
   * Головне, заради чого все переписувалося: усе, що сталося між північчю і
   * третьою ночі за Києвом, за Гринвічем ще вчора.
   */
  it('після місцевої півночі день уже новий, хоча UTC ще вчорашній', () => {
    // 22:30 UTC = 01:30 наступної доби в Києві (влітку UTC+3).
    expect(localDay(new Date('2026-06-15T22:30:00Z'))).toBe('2026-06-16')
  })

  it('узимку зсув на дві години, і межа інша', () => {
    // 22:30 UTC у січні — це 00:30 наступної доби (UTC+2).
    expect(localDay(new Date('2026-01-15T22:30:00Z'))).toBe('2026-01-16')
    // А 21:30 UTC — ще 23:30 того самого дня.
    expect(localDay(new Date('2026-01-15T21:30:00Z'))).toBe('2026-01-15')
  })

  it('приймає і рядок, і мілісекунди, і Date', () => {
    const iso = '2026-06-15T12:00:00Z'
    expect(localDay(iso)).toBe('2026-06-15')
    expect(localDay(Date.parse(iso))).toBe('2026-06-15')
    expect(localDay(new Date(iso))).toBe('2026-06-15')
  })

  it('без аргументу бере поточну мить', () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-06-15T22:30:00Z'))

    expect(localDay()).toBe('2026-06-16')
  })

  it('однозначну дату доповнює нулями', () => {
    expect(localDay(new Date('2026-01-05T12:00:00Z'))).toBe('2026-01-05')
  })

  it('на зіпсованій даті повертає порожньо, а не «NaN-NaN-NaN»', () => {
    expect(localDay('це не дата')).toBeNull()
  })
})

describe('попередній день', () => {
  it('віднімає одну добу', () => {
    expect(dayBefore('2026-06-15')).toBe('2026-06-14')
  })

  it('переходить через межу місяця', () => {
    expect(dayBefore('2026-06-01')).toBe('2026-05-31')
  })

  it('переходить через межу року', () => {
    expect(dayBefore('2026-01-01')).toBe('2025-12-31')
  })

  it('знає про високосний рік', () => {
    expect(dayBefore('2028-03-01')).toBe('2028-02-29')
    expect(dayBefore('2026-03-01')).toBe('2026-02-28')
  })

  /**
   * Не «мінус 24 години»: у ніч переходу на зимовий час доба має 25 годин, на
   * літній — 23. Віднімання доби в мілісекундах двічі на рік давало б не той
   * день — а перехід у Європі саме в неділю, коли дитина цілком може грати.
   */
  it('ніч переходу на літній час не ламає відлік', () => {
    // В Україні перехід на літній — остання неділя березня 2026 (29-те).
    expect(dayBefore('2026-03-30')).toBe('2026-03-29')
    expect(dayBefore('2026-03-29')).toBe('2026-03-28')
  })

  it('ніч переходу на зимовий час не ламає відлік', () => {
    // Остання неділя жовтня 2026 — 25-те.
    expect(dayBefore('2026-10-26')).toBe('2026-10-25')
    expect(dayBefore('2026-10-25')).toBe('2026-10-24')
  })

  it('на зіпсованому дні повертає порожньо', () => {
    expect(dayBefore('не день')).toBeNull()
  })
})
