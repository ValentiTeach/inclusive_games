import { getActiveAdaptations } from './adaptations'

/**
 * Кольори ігор для дитини з порушенням кольорового зору.
 *
 * Ігри задають кольори в конфігах (#c0392b, #2e8b57…), і найгірша пара там —
 * саме червоний і зелений: при дейтеранопії й протанопії вони зливаються в
 * один брудно-жовтий. Тут кожен колір гри замінюється на колір із палітри
 * Окабе–Іто, яку розрізняють при всіх поширених порушеннях кольорового зору.
 *
 * Заміна точкова, а не фільтром на весь екран: фільтр зсунув би й решту
 * інтерфейсу, а форма й підпис лишаються другою ознакою незалежно від кольору.
 */
const SAFE = {
  '#c0392b': '#d55e00', // червоний → цинобровий
  '#d64545': '#d55e00',
  '#2e8b57': '#009e73', // зелений → синьо-зелений
  '#2f9e5f': '#009e73',
  '#2d6bd6': '#0072b2', // синій
  '#c8862b': '#e69f00', // бурштин → помаранчевий
  '#d9a227': '#f0e442', // жовтий світлофора → жовтий
  '#7c5cd9': '#cc79a7', // фіолетовий → рожево-бузковий
  '#1c9099': '#56b4e9', // бірюзовий → небесний
  '#d24b64': '#7a4b00', // кораловий → темно-коричневий
  '#8a5a34': '#6e6e6e', // коричневий → сірий
}

export function safeColorFor(hex) {
  if (typeof hex !== 'string') return hex
  return SAFE[hex.toLowerCase()] ?? hex
}

/** Колір гри з урахуванням профілю дитини. */
export function gameColor(hex) {
  return getActiveAdaptations().colorSafe ? safeColorFor(hex) : hex
}

export function isColorSafe() {
  return getActiveAdaptations().colorSafe
}
