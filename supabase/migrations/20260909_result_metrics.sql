-- Сирі числа поруч із готовими рядками.
--
-- results.entries писався для екрана результатів: кожне значення там — уже
-- готова фраза («85%», «450 мс», «17 / 20»). Через це єдиним числом, яке можна
-- було запитати з бази, лишався score. Точність, час реакції й типи помилок
-- гра рахувала — і тут же ховала в текст, тож ані динаміки по дитині, ані
-- порівняння «швидко але неточно» проти «повільно й точно» побудувати було
-- неможливо. Саме заради цього психолог і дивиться на когнітивні проби.
--
-- Зміна адитивна: entries лишається як був і далі живить екран, metrics стає
-- поруч. Старі записи мають metrics = null — це «не міряли», і avg() їх
-- пропускає сам.
--
-- Ключі описані в src/games/engine/metrics.js. Коротко: snake_case, щоб
-- metrics->>'avg_rt_ms' у SQL не вимагав лапок, і одиниця в назві ключа
-- (_pct, _ms), щоб accuracy_pct у 0–100 не переплуталось із часткою.

alter table public.results add column if not exists metrics jsonb;

comment on column public.results.metrics is
  'Сирі показники спроби: accuracy_pct (0-100), avg_rt_ms, best_rt_ms, total, '
  'correct, errors та специфічні для гри ключі. Відсутній ключ означає "гра '
  'цього не міряє". Готові рядки для показу — в entries. Опис і повний '
  'словник: src/games/engine/metrics.js';
