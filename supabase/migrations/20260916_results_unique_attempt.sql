-- Одна спроба — один рядок.
--
-- До цієї міграції повторний виклик перенесення локальної історії міг записати
-- ті самі спроби вдруге: прапорець «синхронізовано» ставився вже після вставки,
-- а onAuthStateChange спрацьовує більше ніж один раз за вхід. У живій базі це
-- дало три пари однакових рядків. Клієнт уже виправлено, але захист має бути
-- і тут: зіпсовану історію дитини помітно не одразу, а довіряти їй має вчитель.
--
-- Мить гри (played_at) записує клієнт із точністю до мілісекунди, тому два
-- рядки з однаковими user_id, game_id і played_at — це завжди одна спроба,
-- записана двічі, а не дві гри поспіль.
--
-- Індекс не збудується, доки в таблиці лишається бодай одна така пара, тому
-- вже наявні повтори прибираються окремо, за погодженням з власником даних.

create unique index if not exists results_one_attempt_per_moment
  on public.results (user_id, game_id, played_at);
